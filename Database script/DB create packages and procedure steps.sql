  PROCEDURE UPDATE_CONSUMER_PROFILE(
    P_ENTITY_ID      IN NUMBER,
    P_FIRST_NAME     IN VARCHAR2,
    P_LAST_NAME      IN VARCHAR2,
    P_DOB            IN DATE,
    P_EMAIL          IN VARCHAR2,
    P_COUNTRY_ID     IN NUMBER,
    P_OCCUPATION     IN NUMBER,
    P_MONTHLY_INCOME IN NUMBER,
    P_SOF            IN NUMBER,
    P_LEGAL_ID       IN NUMBER,
    P_PERSON_NAME    IN VARCHAR2,
    P_TRADE_NAME     IN VARCHAR2,
    P_LEGAL_NAME     IN VARCHAR2,
    P_DOMAIN         IN VARCHAR2,
    P_REGISTER_NUMBER   IN VARCHAR2,
